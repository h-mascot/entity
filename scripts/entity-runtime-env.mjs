#!/usr/bin/env node
import { chmodSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

export const RUNTIME_ENV_KEYS = [
  'KOKORO_TTS_BASE_URL',
  'KOKORO_TTS_DEFAULT_VOICE',
  'OPENAI_API_KEY',
  'OPENAI_TTS_MODEL',
  'OPENAI_TTS_VOICE',
  'EDGE_TTS_COMMAND',
  'EDGE_TTS_VOICE',
  'EDGE_TTS_TIMEOUT_MS',
  'DEEPGRAM_API_KEY',
  'DEEPGRAM_TTS_VOICE',
  'ELEVENLABS_API_KEY',
  'ELEVENLABS_TTS_VOICE',
  'TTS_MAX_CHARS',
  'ENTITY_PUBLIC_BASE_URL',
  'ENTITY_API_BASE_URL',
  'ENTITY_CLOUD_API_BASE',
  'VITE_ENTITY_API_BASE',
  'VITE_MC_ORIGIN',
  'ENTITY_WS_BASE_URL',
  'VITE_ENTITY_WS_URL',
];

function canonicalRuntimeOrigin(value) {
  if (!value) return '';
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error('ENTITY_BASE_URL must be a canonical http(s) origin.');
  }
  if (!['http:', 'https:'].includes(parsed.protocol)
      || parsed.username
      || parsed.password
      || (parsed.pathname !== '/' && parsed.pathname !== '')
      || parsed.search
      || parsed.hash) {
    throw new Error('ENTITY_BASE_URL must be a canonical http(s) origin.');
  }
  return parsed.origin;
}

function quoteDotenv(value) {
  if (value.includes('\0')) throw new Error('Runtime environment values cannot contain NUL bytes.');
  const candidates = [
    `'${value}'`,
    `"${value.replaceAll('\r', '\\r').replaceAll('\n', '\\n')}"`,
    value,
  ];
  for (const candidate of candidates) {
    if (dotenv.parse(`VALUE=${candidate}\n`).VALUE === value) return candidate;
  }
  throw new Error('Runtime environment value cannot be represented losslessly in dotenv format.');
}

export function serializeRuntimeEnv({ runtimeBaseUrl = '', env = process.env } = {}) {
  const lines = ['# Generated by Entity deploy.sh. Do not commit.'];
  const configuredBaseUrl = String(env.ENTITY_BASE_URL ?? '').trim() || String(runtimeBaseUrl).trim();
  const canonicalBaseUrl = canonicalRuntimeOrigin(configuredBaseUrl);
  if (canonicalBaseUrl) lines.push(`ENTITY_BASE_URL=${quoteDotenv(canonicalBaseUrl)}`);
  for (const key of RUNTIME_ENV_KEYS) {
    const value = env[key];
    if (value !== undefined && value !== '') lines.push(`${key}=${quoteDotenv(String(value))}`);
  }
  return `${lines.join('\n')}\n`;
}

export function writeRuntimeEnv(outputPath, runtimeBaseUrl, env = process.env) {
  writeFileSync(outputPath, serializeRuntimeEnv({ runtimeBaseUrl, env }), { mode: 0o600 });
  chmodSync(outputPath, 0o600);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  const [outputPath, runtimeBaseUrl = ''] = process.argv.slice(2);
  if (!outputPath) {
    console.error('Usage: entity-runtime-env.mjs <output-path> [runtime-base-url]');
    process.exit(64);
  }
  writeRuntimeEnv(outputPath, runtimeBaseUrl);
}
